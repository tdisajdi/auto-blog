MAX_TERMS = 8


def pick(facts_text, limit=MAX_TERMS):
    """자료에 나오는 말만, 자료에 처음 나오는 순서대로."""
    found = []
    for pat, name, meaning in TERMS:
        m = re.search(pat, facts_text or "")
        if m:
            found.append((m.start(), name, meaning))
    return [(n, mean) for _, n, mean in sorted(found)[:limit]]


def block(facts_text):
    terms = pick(facts_text)
    if not terms:
        return ""
    return ("[용어 풀이 - 이 말이 본문에 처음 나올 때 괄호나 한 문장으로 쉽게 풀어 주세요. 뜻은 아래 그대로(다르게 설명하지 말 것). "
            "본문에 안 쓰는 말은 풀지 않아도 됩니다]\n" + "\n".join(f"- {n}: {mean}" for n, mean in terms) + "\n")
